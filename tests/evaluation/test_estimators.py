"""Tests for the WOSAC probability estimators.

Golden values were generated by executing the official waymo-open-dataset
reference (``wdl_limited/sim_agents_metrics/estimators.py``, TF/TFP) on
these exact inputs; the JAX port must reproduce them.
"""

from __future__ import annotations

import jax
import jax.numpy as jnp
import pytest

from diffav.core.constants import (
    FeatureEstimateConfig,
    HistogramEstimateConfig,
)
from diffav.evaluation.estimators import (
    bernoulli_log_likelihood,
    histogram_log_likelihood,
    log_likelihood_estimate_scenario_level,
    log_likelihood_estimate_timeseries,
)


_HIST_CONFIG = HistogramEstimateConfig(
    min_val=0.0, max_val=4.0, num_bins=4, additive_smoothing_pseudocount=0.1
)


class TestHistogramLogLikelihood:
    """Reference-golden tests for the histogram estimator."""

    def test_basic_counts_match_reference(self) -> None:
        """Known bin counts with pseudocount smoothing."""
        sim = jnp.array([[0.5, 1.5, 1.7, 2.5, 3.5, 3.9]])
        log = jnp.array([[0.5, 1.2, 2.9, 3.1]])
        result = histogram_log_likelihood(_HIST_CONFIG, log, sim)
        expected = jnp.array([[-1.7609878, -1.1143607, -1.7609878, -1.1143607]])
        assert jnp.allclose(result, expected, atol=1e-5)

    def test_clipping_at_both_edges_matches_reference(self) -> None:
        """Out-of-range samples clip into the boundary bins."""
        sim = jnp.array([[-1.0, 0.2, 5.0, 4.0]])
        log = jnp.array([[-3.0, 9.0]])
        result = histogram_log_likelihood(_HIST_CONFIG, log, sim)
        expected = jnp.array([[-0.73966724, -0.73966724]])
        assert jnp.allclose(result, expected, atol=1e-5)

    def test_nan_sim_samples_land_in_last_bin(self) -> None:
        """NaN sim samples are bucketed into the last bin, as the reference does."""
        sim = jnp.array([[0.5, jnp.nan, 1.7, 2.5, jnp.nan, 3.9]])
        log = jnp.array([[0.5, 1.2, 2.9, 3.1]])
        result = histogram_log_likelihood(_HIST_CONFIG, log, sim)
        expected = jnp.array([[-1.7609878, -1.7609878, -1.7609878, -0.72489595]])
        assert jnp.allclose(result, expected, atol=1e-5)

    def test_jit_and_vmap_compatible(self) -> None:
        """The estimator traces under jit and vmaps over a scenario axis."""
        sim = jnp.array([[0.5, 1.5, 1.7, 2.5, 3.5, 3.9]])
        log = jnp.array([[0.5, 1.2, 2.9, 3.1]])
        jitted = jax.jit(lambda lo, si: histogram_log_likelihood(_HIST_CONFIG, lo, si))
        assert jnp.allclose(jitted(log, sim), histogram_log_likelihood(_HIST_CONFIG, log, sim))

        batched_log = jnp.stack([log, log + 1.0])
        batched_sim = jnp.stack([sim, sim])
        batched = jax.vmap(lambda lo, si: histogram_log_likelihood(_HIST_CONFIG, lo, si))(
            batched_log, batched_sim
        )
        assert batched.shape == (2, 1, 4)
        assert jnp.allclose(batched[0], histogram_log_likelihood(_HIST_CONFIG, log, sim))


class TestBernoulliLogLikelihood:
    """Reference-golden tests for the bernoulli estimator."""

    def test_mixed_booleans_match_reference(self) -> None:
        """Bernoulli scoring via two unit bins with smoothing."""
        log = jnp.array([[True, False]])
        sim = jnp.array([[True, True, False, True]])
        result = bernoulli_log_likelihood(0.1, log, sim)
        expected = jnp.array([[-0.30368242, -1.3397743]])
        assert jnp.allclose(result, expected, atol=1e-5)


class TestLogLikelihoodEstimateTimeseries:
    """Reference-golden tests for the time-series estimation flow."""

    def _inputs(self) -> tuple[jax.Array, jax.Array]:
        log = jnp.array([[1.0, 3.0, 5.0], [2.0, 2.0, 9.0]])  # (N=2, T=3)
        sim = jnp.array(
            [
                [[1.0, 1.5, 3.0], [2.0, 2.5, 8.5]],
                [[0.5, 3.5, 5.5], [1.5, 2.2, 9.5]],
            ]
        )  # (K=2, N=2, T=3)
        return log, sim

    def test_independent_timesteps_pools_rollouts_and_steps(self) -> None:
        """With independent timesteps, sim pools to one distribution per agent."""
        config = FeatureEstimateConfig(
            histogram=HistogramEstimateConfig(
                min_val=0.0, max_val=10.0, num_bins=5, additive_smoothing_pseudocount=0.1
            ),
            independent_timesteps=True,
            metametric_weight=0.05,
        )
        log, sim = self._inputs()
        result = log_likelihood_estimate_timeseries(config, log, sim)
        expected = jnp.array(
            [
                [-0.74040014, -1.1298649, -1.7764919],
                [-0.7404, -0.7404, -1.1298647],
            ]
        )
        assert jnp.allclose(result, expected, atol=1e-5)

    def test_per_step_branch_matches_reference(self) -> None:
        """Without independent timesteps, each step is scored per-step."""
        config = FeatureEstimateConfig(
            histogram=HistogramEstimateConfig(
                min_val=0.0, max_val=10.0, num_bins=5, additive_smoothing_pseudocount=0.1
            ),
            independent_timesteps=False,
            metametric_weight=0.05,
        )
        log, sim = self._inputs()
        result = log_likelihood_estimate_timeseries(config, log, sim)
        expected = jnp.array(
            [
                [-0.17435358, -0.8209804, -0.8209804],
                [-0.8209804, -0.17435358, -0.17435338],
            ]
        )
        assert jnp.allclose(result, expected, atol=1e-5)


class TestLogLikelihoodEstimateScenarioLevel:
    """Reference-golden test for time-aggregated (indication) features."""

    def test_bernoulli_indications_match_reference(self) -> None:
        """Scenario-level bernoulli via the dummy-time-axis path."""
        config = FeatureEstimateConfig(
            bernoulli_pseudocount=0.1,
            metametric_weight=0.25,
        )
        log = jnp.array([False, True])  # (N=2,)
        sim = jnp.array([[False, True], [False, False], [True, True]])  # (K=3, N=2)
        result = log_likelihood_estimate_scenario_level(config, log, sim)
        expected = jnp.array([-0.42121348, -0.42121348])
        assert jnp.allclose(result, expected, atol=1e-5)

    def test_perfect_agreement_scores_higher_than_disagreement(self) -> None:
        """Log values matching the sim majority score higher."""
        config = FeatureEstimateConfig(bernoulli_pseudocount=0.1, metametric_weight=0.25)
        sim = jnp.array([[False, False], [False, False], [False, False]])
        agree = log_likelihood_estimate_scenario_level(config, jnp.array([False, False]), sim)
        disagree = log_likelihood_estimate_scenario_level(config, jnp.array([True, True]), sim)
        assert float(jnp.sum(agree)) > float(jnp.sum(disagree))


class TestFeatureEstimateConfigValidation:
    """Config-shape validation for the estimator dispatch."""

    def test_histogram_config_is_histogram_estimator(self) -> None:
        """A histogram-bearing config dispatches to the histogram estimator."""
        config = FeatureEstimateConfig(
            histogram=HistogramEstimateConfig(
                min_val=0.0, max_val=1.0, num_bins=2, additive_smoothing_pseudocount=0.1
            ),
            metametric_weight=0.1,
        )
        assert config.histogram is not None

    def test_bernoulli_config_has_no_histogram(self) -> None:
        """A bernoulli config carries no histogram spec."""
        config = FeatureEstimateConfig(bernoulli_pseudocount=0.1, metametric_weight=0.25)
        assert config.histogram is None

    def test_configs_are_frozen(self) -> None:
        """Estimate configs are immutable value objects."""
        with pytest.raises(AttributeError):
            _HIST_CONFIG.num_bins = 5  # type: ignore[misc]
