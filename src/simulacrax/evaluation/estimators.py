"""JAX ports of the WOSAC probability estimators.

Line-by-line ports of the official waymo-open-dataset
``wdl_limited/sim_agents_metrics/estimators.py`` histogram and bernoulli
estimators, validated against golden values generated by executing the
reference implementation. The kernel-density estimator is not ported: the
2025 sim-agents challenge configuration uses only histogram and bernoulli
features.

All functions are pure JAX — jit- and vmap-compatible. NaN samples (the
central-difference boundary pads) are bucketed into the last histogram
bin, exactly as the reference behaves.
"""

from __future__ import annotations

import jax
import jax.numpy as jnp

from simulacrax.core.constants import FeatureEstimateConfig, HistogramEstimateConfig


def _bin_indices(config: HistogramEstimateConfig, samples: jax.Array) -> jax.Array:
    """Assign each clipped sample to its histogram bin.

    Bins are right-open except the last, which includes ``max_val`` —
    matching the reference's TFP histogram semantics. NaN sorts past every
    edge and lands in the last bin, as the reference does.
    """
    edges = jnp.linspace(config.min_val, config.max_val, config.num_bins + 1)
    clipped = jnp.clip(samples, config.min_val, config.max_val)
    indices = jnp.searchsorted(edges, clipped, side="right") - 1
    return jnp.clip(indices, 0, config.num_bins - 1)


def histogram_log_likelihood(
    config: HistogramEstimateConfig,
    log_samples: jax.Array,
    sim_samples: jax.Array,
) -> jax.Array:
    """Log-likelihood of log samples under per-row sim histograms.

    For each of the ``batch_size`` independent populations, buckets the
    sim samples into ``num_bins`` equal bins, applies additive smoothing,
    normalizes to a categorical distribution, and scores each log sample's
    bin under it.

    Args:
        log_samples: Samples to score, shape ``(batch_size, log_sample_size)``.
        sim_samples: Samples defining the distributions, shape
            ``(batch_size, sim_sample_size)``.
        config: Histogram estimator specification.

    Returns:
        Log-likelihoods with shape ``(batch_size, log_sample_size)``.
    """
    sim_bins = _bin_indices(config, sim_samples)  # (B, S)
    # One-hot summation gives deterministic per-row bin counts.
    counts = jnp.sum(jax.nn.one_hot(sim_bins, config.num_bins), axis=1)  # (B, bins)
    smoothed = counts + config.additive_smoothing_pseudocount
    log_probs = jnp.log(smoothed / jnp.sum(smoothed, axis=-1, keepdims=True))

    log_bins = _bin_indices(config, log_samples)  # (B, L)
    return jnp.take_along_axis(log_probs, log_bins, axis=-1)


def bernoulli_log_likelihood(
    pseudocount: float,
    log_samples: jax.Array,
    sim_samples: jax.Array,
) -> jax.Array:
    """Log-probability of boolean log samples under per-row sim Bernoullis.

    Implemented, as in the reference, via a two-unit-bin histogram over
    ``[-0.5, 1.5]`` on the booleans cast to floats.

    Args:
        pseudocount: Additive smoothing count per outcome.
        log_samples: Boolean samples to score, shape ``(batch_size, L)``.
        sim_samples: Boolean samples defining the distributions, shape
            ``(batch_size, S)``.

    Returns:
        Log-probabilities with shape ``(batch_size, L)``.
    """
    histogram = HistogramEstimateConfig(
        min_val=-0.5, max_val=1.5, num_bins=2, additive_smoothing_pseudocount=pseudocount
    )
    return histogram_log_likelihood(
        histogram, log_samples.astype(jnp.float32), sim_samples.astype(jnp.float32)
    )


def _estimate(
    config: FeatureEstimateConfig,
    log_samples: jax.Array,
    sim_samples: jax.Array,
) -> jax.Array:
    """Dispatch to the estimator selected by the feature config."""
    if config.histogram is not None:
        return histogram_log_likelihood(config.histogram, log_samples, sim_samples)
    return bernoulli_log_likelihood(config.bernoulli_pseudocount, log_samples, sim_samples)


def log_likelihood_estimate_timeseries(
    config: FeatureEstimateConfig,
    log_values: jax.Array,
    sim_values: jax.Array,
) -> jax.Array:
    """Agent-level log-likelihood estimates for a time-series feature.

    With ``independent_timesteps`` (all 2025 time-series features), the sim
    rollouts and steps pool into one distribution per agent; otherwise each
    step is scored against the per-step rollout distribution.

    Args:
        config: Feature estimator specification.
        log_values: Logged feature values, shape ``(num_agents, num_steps)``.
        sim_values: Simulated feature values, shape
            ``(num_rollouts, num_agents, num_steps)``.

    Returns:
        Log-likelihoods with shape ``(num_agents, num_steps)``.
    """
    num_rollouts, num_agents, num_steps = sim_values.shape
    if config.independent_timesteps:
        pooled = jnp.transpose(sim_values, (1, 0, 2)).reshape(num_agents, num_rollouts * num_steps)
        return _estimate(config, log_values, pooled)

    per_step_sim = jnp.transpose(sim_values, (1, 2, 0)).reshape(
        num_agents * num_steps, num_rollouts
    )
    per_step_log = log_values.reshape(num_agents * num_steps, 1)
    return _estimate(config, per_step_log, per_step_sim).reshape(num_agents, num_steps)


def log_likelihood_estimate_scenario_level(
    config: FeatureEstimateConfig,
    log_values: jax.Array,
    sim_values: jax.Array,
) -> jax.Array:
    """Log-likelihood estimates for time-aggregated (indication) features.

    Args:
        config: Feature estimator specification.
        log_values: Logged per-agent values, shape ``(num_agents,)``.
        sim_values: Simulated per-agent values, shape
            ``(num_rollouts, num_agents)``.

    Returns:
        Log-likelihoods with shape ``(num_agents,)``.
    """
    timeseries = log_likelihood_estimate_timeseries(
        config, log_values[..., jnp.newaxis], sim_values[..., jnp.newaxis]
    )
    return timeseries[..., 0]
